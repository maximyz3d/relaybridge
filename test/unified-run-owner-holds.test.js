'use strict';
// Physical-owner writer holds through the real server.js wiring. A TEST FAKE
// preload, generated here into a temporary directory, wraps the owned
// execution backend so heldWorkspaces() returns rows from a file (or throws);
// every other backend member is the real one. No ownership is enrolled and no
// public API changes. The exact private task/reservation/owner exemption needs
// an owned private context, which only owned enrollment creates, so it is
// proven on real owner rows in test/owned-execution-backend.test.js.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { startTestBridge, completeJsonLines, waitFor } = require('./helpers/temporary-bridge');
const { isolatedEnv } = require('./helpers/isolated-env');
const ROOT = path.resolve(__dirname, '..');
const linuxOnly = { skip: process.platform !== 'linux' && 'unified run durability is Linux-only' };

function writePreload(dir, rowsFile) {
  const file = path.join(dir, 'test-fake-owner-rows-preload.js');
  fs.writeFileSync(file, `'use strict';
// TEST FAKE: generated by test/unified-run-owner-holds.test.js. Never loaded by production.
const fs = require('fs');
require(${JSON.stringify(path.join(ROOT, 'test', 'helpers', 'deny-egress.js'))});
const owned = require(${JSON.stringify(path.join(ROOT, 'lib', 'owned-execution-backend.js'))});
const original = owned.createOwnedExecutionBackend;
owned.createOwnedExecutionBackend = (options) => {
  const real = original(options);
  return Object.freeze({ ...real, heldWorkspaces: () => {
    const text = fs.existsSync(${JSON.stringify(rowsFile)}) ? fs.readFileSync(${JSON.stringify(rowsFile)}, 'utf8') : '[]';
    if (text.trim() === 'throw') throw Object.assign(new Error('TEST FAKE authority unavailable'), { code: 'OWNER_BACKEND_UNAVAILABLE' });
    return JSON.parse(text).map((row) => Object.freeze(row));
  } });
};
`);
  return file;
}

function fixtureConfig(root) {
  const events = path.join(root, 'events.jsonl');
  const script = path.join(root, 'fixture.js');
  fs.writeFileSync(script, `const fs=require('fs');fs.appendFileSync(${JSON.stringify(events)},JSON.stringify({kind:process.argv[2],cwd:process.cwd()})+'\\n');console.log('fixture answer');`);
  const slot = [process.execPath, script, 'claude', '--model', 'fixture', '--effort', 'medium', '{prompt}'];
  return { _models: { discoverOnBoot: false }, claude: { label: 'Offline claude fixture', safe: slot, dangerous: slot, oneshot_safe: slot, oneshot_dangerous: slot,
    capabilities: ['prompt'], oneshot_safe_filesystem_policy: 'read_only_enforced',
    oneshot_capabilities: { safe: ['model_invocation', 'workspace_read', 'tool_use'], dangerous: ['model_invocation', 'workspace_read', 'workspace_write', 'tool_use'] },
    cost_class: 'subscription', model: 'fixture' } };
}

async function ownerFixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rb-owner-rows-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const rowsFile = path.join(dir, 'rows.json');
  let ws, other;
  const bridge = await startTestBridge(t, (root) => {
    ws = path.join(root, 'ws'); other = path.join(root, 'other');
    fs.mkdirSync(path.join(ws, 'sub'), { recursive: true }); fs.mkdirSync(other);
    for (const cwd of [ws, other]) execFileSync('git', ['init', '-q'], { cwd, env: isolatedEnv() });
    return fixtureConfig(root);
  }, { nodeArgs: ['--require', writePreload(dir, rowsFile)], env: { RELAYBRIDGE_WARM_DIAG: '0', RELAYBRIDGE_REMOTE_MCP: '0' } });
  ws = fs.realpathSync(ws); other = fs.realpathSync(other);
  const rows = (value) => fs.writeFileSync(rowsFile, typeof value === 'string' ? value : JSON.stringify(value));
  const row = (cwd, patch = {}) => ({ cwd, taskId: 't_fake_owner', reservationId: 'qr_fake', ownerId: 'owner_fake', ...patch });
  const events = () => completeJsonLines(path.join(bridge.root, 'events.jsonl'));
  const usage = async () => {
    const reset = Math.floor(Date.now() / 1000) + 18000;
    const result = await bridge.request('/api/usage/native', { kind: 'claude', accountId: 'default', rate_limits: {
      five_hour: { used_percentage: 10, resets_at: reset }, seven_day: { used_percentage: 10, resets_at: reset + 604800 } } });
    assert.equal(result.status, 200, JSON.stringify(result.body));
  };
  const oneshot = (cwd, dangerous = true) => bridge.request('/api/oneshot', { kind: 'claude', prompt: 'EDIT', cwd, effort: 'low',
    ...(dangerous ? { dangerous: true, acknowledgeFilesystemWrites: true } : { dangerous: false }) });
  return { ...bridge, ws, sub: path.join(ws, 'sub'), other, rows, row, events, usage, oneshot };
}

const assertOwnerHeld = (response, id, label) => {
  assert.equal(response.status, 409, `${label}: ${JSON.stringify(response.body)}`);
  assert.equal(response.body.errorCode, 'workspace_writer_busy', `${label}: ${JSON.stringify(response.body)}`);
  assert.deepEqual(response.body.holder, { holder: 'physical_owner', id }, label);
};

test('server one-shot and queued writers respect physical owner rows: overlap holds, siblings run, a bare task id is not an exemption, unavailable authority holds all', { timeout: 90000 }, async (t) => {
  const f = await ownerFixture(t);
  // A child owner holds a parent writer; a parent owner holds a child writer.
  f.rows([f.row(f.sub, { ownerId: 'owner_child' })]);
  assertOwnerHeld(await f.oneshot(f.ws), 'owner_child', 'parent one-shot');
  f.rows([f.row(f.ws, { ownerId: 'owner_parent' })]);
  assertOwnerHeld(await f.oneshot(f.sub), 'owner_parent', 'child one-shot');
  assertOwnerHeld(await f.oneshot(f.ws), 'owner_parent', 'same one-shot');
  assert.equal(f.events().length, 0);
  // Read-only work and a sibling writer are not held.
  assert.equal((await f.oneshot(f.ws, false)).status, 200);
  const sibling = await f.oneshot(f.other);
  assert.equal(sibling.status, 200, JSON.stringify(sibling.body));
  assert.equal(f.events().length, 2);

  // A queued writer whose task id, and even reservation, match the owner row
  // is still held: only an owner-bound private context is exempt.
  const taskId = 't_fake_owner_mismatch';
  f.rows([f.row(f.ws, { taskId, reservationId: null, ownerId: 'owner_mismatch' })]);
  const queued = await f.request('/api/tasks', { kind: 'claude', prompt: 'EDIT', cwd: f.ws, dangerous: true, acknowledgeFilesystemWrites: true,
    effort: 'low', deliveryMode: 'queued', taskId });
  assert.equal(queued.status, 202, JSON.stringify(queued.body));
  const settled = await waitFor(async () => {
    const task = (await f.request(`/api/tasks/${taskId}`)).body;
    return ['done', 'failed', 'cancelled', 'interrupted'].includes(task.status) && task;
  }, 30000);
  assert.notEqual(settled.status, 'done', JSON.stringify(settled));
  assert.match(JSON.stringify(settled), /workspace_writer_busy/);
  assert.match(JSON.stringify(settled), /owner_mismatch/);
  assert.equal(f.events().length, 2);

  // Unavailable owner authority holds every workspace, disjoint ones included.
  f.rows('throw');
  for (const cwd of [f.ws, f.other]) assertOwnerHeld(await f.oneshot(cwd), null, `unavailable ${cwd}`);
  assert.equal((await f.oneshot(f.other, false)).status, 200);
  f.rows([]);
  assert.equal((await f.oneshot(f.other)).status, 200);
  assert.equal(f.events().length, 4);
});

test('server unified writer runs respect physical owner rows at create', { ...linuxOnly, timeout: 90000 }, async (t) => {
  const f = await ownerFixture(t);
  await f.usage();
  const writer = (cwd) => f.request('/api/unified-runs', { objective: 'EDIT', cwd, dangerous: true, acknowledgeFilesystemWrites: true,
    segments: [{ kind: 'claude', accountId: 'default', transport: 'native', model: 'fixture', effort: 'low' }] });
  const runs = () => { const dir = path.join(f.root, 'data', 'unified-runs'); return fs.existsSync(dir) ? fs.readdirSync(dir) : []; };
  f.rows([f.row(f.sub, { ownerId: 'owner_child' })]);
  assertOwnerHeld(await writer(f.ws), 'owner_child', 'parent run');
  f.rows([f.row(f.ws, { ownerId: 'owner_parent' })]);
  assertOwnerHeld(await writer(f.sub), 'owner_parent', 'child run');
  f.rows('throw');
  assertOwnerHeld(await writer(f.other), null, 'unavailable authority');
  assert.deepEqual(runs(), []);
  assert.equal(f.events().length, 0);
  // A sibling owner leaves the writer free to run.
  f.rows([f.row(f.other)]);
  const created = await writer(f.ws);
  assert.equal(created.status, 202, JSON.stringify(created.body));
  const done = await waitFor(async () => { const view = (await f.request(`/api/unified-runs/${created.body.id}`)).body; return view.state !== 'running' && view; }, 30000);
  assert.equal(done.state, 'complete', JSON.stringify(done));
  assert.equal(f.events().length, 1);
});
