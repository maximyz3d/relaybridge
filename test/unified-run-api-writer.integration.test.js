// API-only writer runs through the real server.js unified-run and API-agent
// paths. A TEST FAKE preload, generated here into a temporary directory,
// supplies an openai qualification adapter and a scripted Responses provider;
// deny-egress is also preloaded. No real provider is contacted and no real
// credential is read: the reserved env var holds a sentinel.
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const crypto = require('node:crypto');
const { startTestBridge, completeJsonLines, waitFor } = require('./helpers/temporary-bridge');
const { CREDIT_SECRET_NAMES } = require('../lib/allocated-credit');
const ROOT = path.resolve(__dirname, '..');
const SENTINEL = 'sk-api-writer-sentinel-must-never-appear';
const linuxOnly = { skip: process.platform !== 'linux' && 'API workspace writes are Linux-only' };
const sha = (text) => crypto.createHash('sha256').update(text).digest('hex');

// Each provider request answers the next scripted step. A patch step hashes
// the workspace file at request time, as a model that has read it would.
function writePreload(dir, { scriptFile, fetchLog, qualified }) {
  const file = path.join(dir, 'test-fake-preload.js');
  fs.writeFileSync(file, `'use strict';
// TEST FAKE: generated by test/unified-run-api-writer.integration.test.js. Never loaded by production.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
require(${JSON.stringify(path.join(ROOT, 'test', 'helpers', 'deny-egress.js'))});
${qualified ? `const qualification = require(${JSON.stringify(path.join(ROOT, 'lib', 'api-agent-qualification.js'))});
const original = qualification.createQualificationAuthority;
qualification.createQualificationAuthority = () => original({ adapters: { openai: () => ({ qualified: true, qualificationId: 'q_test_fake' }) } });` : ''}
const realFetch = globalThis.fetch;
const usage = { input_tokens: 100, input_tokens_details: { cached_tokens: 0 }, output_tokens: 10, output_tokens_details: { reasoning_tokens: 0 }, total_tokens: 110 };
globalThis.fetch = async (input, init) => {
  const url = new URL(String(input && input.url ? input.url : input));
  if (/^(127\\.|localhost$|\\[::1\\]$)/.test(url.hostname)) return realFetch(input, init);
  const step = completed();
  const script = JSON.parse(fs.readFileSync(${JSON.stringify(scriptFile)}, 'utf8'));
  const spec = script.steps[step] || { text: 'TEST FAKE script exhausted' };
  const body = JSON.parse(init.body);
  fs.appendFileSync(${JSON.stringify(fetchLog)}, JSON.stringify({ host: url.hostname, step, tools: (body.tools || []).map((t) => t.name).sort(),
    outputs: (body.input || []).filter((i) => i.type === 'function_call_output').map((i) => i.output) }) + '\\n');
  const output = [];
  if (spec.text) output.push({ type: 'message', id: 'msg_' + step, role: 'assistant', status: 'completed', content: [{ type: 'output_text', text: spec.text, annotations: [] }] });
  if (spec.read) output.push({ type: 'function_call', id: 'fc_' + step, call_id: 'call_read_' + step, name: 'read_file', status: 'completed',
    arguments: JSON.stringify({ path: spec.read, offset: null, length: null }) });
  if (spec.patch) {
    const current = fs.readFileSync(path.join(script.cwd, spec.patch.path));
    output.push({ type: 'function_call', id: 'fc_' + step, call_id: 'call_patch_' + step, name: 'apply_patch', status: 'completed',
      arguments: JSON.stringify({ path: spec.patch.path, expectedSha256: crypto.createHash('sha256').update(current).digest('hex'), edits: spec.patch.edits }) });
  }
  return new Response(JSON.stringify({ id: 'resp_' + step, object: 'response', status: 'completed', model: 'gpt-5', output, usage }),
    { status: 200, headers: { 'content-type': 'application/json' } });
};
function completed() { try { return fs.readFileSync(${JSON.stringify(fetchLog)}, 'utf8').split('\\n').filter(Boolean).length; } catch { return 0; } }
`);
  return file;
}

function fixtureConfig(root) {
  const events = path.join(root, 'events.jsonl');
  const script = path.join(root, 'fixture.js');
  fs.writeFileSync(script, `require('fs').appendFileSync(${JSON.stringify(events)}, JSON.stringify({ kind: process.argv[2] }) + '\\n'); console.log('fixture answer');`);
  const entry = (kind, model = 'fixture') => {
    const slot = [process.execPath, script, kind, '--model', model, '--effort', 'medium', '{prompt}'];
    return { label: `Offline ${kind} fixture`, safe: slot, dangerous: slot, oneshot_safe: slot, oneshot_dangerous: slot,
      capabilities: ['prompt'], oneshot_safe_filesystem_policy: 'read_only_enforced',
      oneshot_capabilities: { safe: ['model_invocation', 'workspace_read', 'tool_use'], dangerous: ['model_invocation', 'workspace_read', 'workspace_write', 'tool_use'] },
      cost_class: 'subscription', model };
  };
  return { _models: { discoverOnBoot: false }, claude: entry('claude'), codex: entry('codex', 'gpt-5') };
}

async function writerBridge(t, { qualified = true } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rb-api-writer-fake-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const files = { scriptFile: path.join(dir, 'script.json'), fetchLog: path.join(dir, 'fetch.jsonl'), egressLog: path.join(dir, 'egress.log') };
  const preload = writePreload(dir, { ...files, qualified });
  let ws;
  const bridge = await startTestBridge(t, (root) => {
    ws = path.join(fs.realpathSync(root), 'ws');
    fs.mkdirSync(path.join(ws, 'src'), { recursive: true });
    fs.writeFileSync(path.join(ws, 'src', 'app.js'), 'export const greeting = "hello";\n');
    fs.writeFileSync(path.join(ws, 'README.md'), 'untouched\n');
    fs.writeFileSync(path.join(ws, '.env'), 'TOKEN=x\n');
    return fixtureConfig(root);
  }, { nodeArgs: ['--require', preload], env: { RELAYBRIDGE_WARM_DIAG: '0', RELAYBRIDGE_REMOTE_MCP: '0',
    [CREDIT_SECRET_NAMES[1]]: SENTINEL, DENY_EGRESS_LOG: files.egressLog } });
  const saved = await bridge.request('/api/funding-profiles', { expectedRevision: (await bridge.request('/api/funding-profiles')).body.storeRevision,
    profile: { id: 'api_openai', provider: 'openai', label: 'api_openai', subscription: { kind: 'codex', accountId: 'default' },
      organization: { ref: 'org_api_openai', label: 'Fixture org' }, project: { ref: 'project_api_openai', label: 'Fixture project' },
      credentialRef: { type: 'reserved_env', name: CREDIT_SECRET_NAMES[1] },
      creditPeriod: { start: '2020-01-01T00:00:00.000Z', end: '2099-01-01T00:00:00.000Z' } } });
  assert.equal(saved.status, 200, JSON.stringify(saved.body));
  const revision = saved.body.profiles?.find?.((p) => p.id === 'api_openai')?.revision ?? 1;
  const apiSegment = { kind: 'codex', accountId: 'default', transport: 'api', model: 'gpt-5', effort: 'medium', fundingProfileId: 'api_openai',
    expectedProfileRevision: revision };
  const script = (steps) => fs.writeFileSync(files.scriptFile, JSON.stringify({ cwd: ws, steps }));
  const fetches = () => completeJsonLines(files.fetchLog);
  const view = async (id) => (await bridge.request(`/api/unified-runs/${id}`)).body;
  const create = (body) => bridge.request('/api/unified-runs', { cwd: ws, segments: [apiSegment], ...body });
  const settled = (id) => waitFor(async () => { const v = await view(id); return !['running', 'planning'].includes(v.state) && v.segments?.[0]
    && !['intent', 'not_submitted', 'dispatched'].includes(v.segments[0].state) && v; }, 30000);
  const read = (rel) => fs.readFileSync(path.join(ws, rel), 'utf8');
  return { ...bridge, ws, files, apiSegment, script, fetches, view, create, settled, read };
}

const noEgress = (bridge) => assert.equal(fs.existsSync(bridge.files.egressLog) ? fs.readFileSync(bridge.files.egressLog, 'utf8') : '', '');
const noSentinel = (bridge) => {
  const walk = (dir) => fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name)) : e.isFile() ? [path.join(dir, e.name)] : []) : [];
  for (const file of walk(path.join(bridge.root, 'data'))) assert.equal(fs.readFileSync(file, 'utf8').includes(SENTINEL), false, file);
};
const writerBody = { objective: 'Change the greeting', dangerous: true, acknowledgeFilesystemWrites: true, allowedWritePaths: ['src/app.js'] };

test('an API-only writer run reads and edits an allowed existing file and reports the real boundary', { ...linuxOnly, timeout: 90000 }, async (t) => {
  const bridge = await writerBridge(t);
  bridge.script([{ read: 'src/app.js' }, { patch: { path: 'src/app.js', edits: [{ oldText: '"hello"', newText: '"hello, world"' }] } },
    { text: 'Updated the greeting.' }]);
  const created = await bridge.create(writerBody);
  assert.equal(created.status, 202, JSON.stringify(created.body));
  assert.equal(created.body.writeBoundary, 'per_segment');
  assert.deepEqual(created.body.allowedWritePaths, ['src/app.js']);
  const done = await bridge.settled(created.body.id);
  assert.equal(done.segments[0].state, 'settled', JSON.stringify(done));
  assert.equal(bridge.read('src/app.js'), 'export const greeting = "hello, world";\n');
  assert.equal(bridge.read('README.md'), 'untouched\n');
  assert.deepEqual(fs.readdirSync(bridge.ws).sort(), ['.env', 'README.md', 'src']);
  assert.deepEqual(fs.readdirSync(path.join(bridge.ws, 'src')), ['app.js'], 'no temp or new file remains');

  const segment = done.segments[0];
  assert.equal(segment.writeBoundary.kind, 'in_process_tool_contract');
  assert.equal(segment.writeBoundary.osSandbox, false);
  assert.equal(segment.writeBoundary.atomicCompareAndSwap, false);
  assert.match(segment.apiCheckpointRunId, /^aar_/);

  const task = (await bridge.request(`/api/tasks/${segment.taskId}`)).body;
  const apiAgent = task.route?.api_agent ?? task.result?.route?.api_agent;
  assert.ok(apiAgent, JSON.stringify(task));
  assert.equal(apiAgent.checkpoint_run_id, segment.apiCheckpointRunId);
  assert.deepEqual(apiAgent.allowed_write_paths, ['src/app.js']);
  assert.equal(apiAgent.write_boundary.kind, 'in_process_tool_contract');
  assert.equal(apiAgent.patches.length, 1);
  assert.deepEqual({ path: apiAgent.patches[0].path, state: apiAgent.patches[0].state, pre: apiAgent.patches[0].preSha256, post: apiAgent.patches[0].postSha256 },
    { path: 'src/app.js', state: 'committed', pre: sha('export const greeting = "hello";\n'), post: sha('export const greeting = "hello, world";\n') });
  assert.deepEqual(apiAgent.effects_pending, []);

  const fetches = bridge.fetches();
  assert.equal(fetches.length, 3);
  assert.ok(fetches.every((f) => f.host === 'api.openai.com'));
  // The writer toolset is the read tools plus apply_patch: no create, delete or shell tool.
  assert.deepEqual(fetches[0].tools, ['apply_patch', 'list_dir', 'read_file', 'search']);
  assert.match(fetches[2].outputs.at(-1), /"applied":true/);
  noEgress(bridge); noSentinel(bridge);
});

test('an API run without a write contract is read-only and offers no patch tool', { ...linuxOnly, timeout: 90000 }, async (t) => {
  const bridge = await writerBridge(t);
  bridge.script([{ patch: { path: 'src/app.js', edits: [{ oldText: '"hello"', newText: '"bye"' }] } }, { text: 'done' }]);
  const created = await bridge.create({ objective: 'Read only review' });
  assert.equal(created.status, 202, JSON.stringify(created.body));
  const done = await bridge.settled(created.body.id);
  assert.notEqual(done.segments[0].writeBoundary.kind, 'in_process_tool_contract', JSON.stringify(done.segments[0]));
  assert.equal(bridge.read('src/app.js'), 'export const greeting = "hello";\n');
  assert.ok(bridge.fetches().length >= 1);
  assert.equal(bridge.fetches()[0].tools.includes('apply_patch'), false);
  noEgress(bridge); noSentinel(bridge);
});

test('write contracts are refused before any effect when unsafe or unsupported', { ...linuxOnly, timeout: 60000 }, async (t) => {
  const bridge = await writerBridge(t);
  bridge.script([{ text: 'must never run' }]);
  const native = { kind: 'claude', accountId: 'default', transport: 'native', model: 'fixture', effort: 'low' };
  for (const [label, body, status, code] of [
    ['hidden', { ...writerBody, allowedWritePaths: ['.env'] }, 400, 'invalid_write_contract'],
    ['secret', { ...writerBody, allowedWritePaths: ['config/server.pem'] }, 400, 'invalid_write_contract'],
    ['traversal', { ...writerBody, allowedWritePaths: ['../outside.txt'] }, 400, null],
    ['empty', { ...writerBody, allowedWritePaths: [] }, 400, null],
    ['no ack', { ...writerBody, acknowledgeFilesystemWrites: false }, 400, 'filesystem_acknowledgement_required'],
    ['not dangerous', { ...writerBody, dangerous: false }, 400, 'filesystem_acknowledgement_required'],
    ['native segment', { ...writerBody, segments: [native, bridge.apiSegment] }, 409, 'filesystem_contract_unsupported'],
    ['competing transport field', { ...writerBody, transports: ['api'] }, 400, null],
  ]) {
    const refused = await bridge.create(body);
    assert.equal(refused.status, status, `${label}: ${JSON.stringify(refused.body)}`);
    if (code) assert.equal(refused.body.code ?? refused.body.errorCode ?? refused.body.error, code, `${label}: ${JSON.stringify(refused.body)}`);
  }
  assert.equal(fs.existsSync(path.join(bridge.root, 'data', 'unified-runs')) ? fs.readdirSync(path.join(bridge.root, 'data', 'unified-runs')).length : 0, 0);
  // The public one-shot path cannot assert a writer reference.
  const spoof = await bridge.request('/api/oneshot', { kind: 'codex', prompt: 'spoof', cwd: bridge.ws, dangerous: true,
    unifiedRun: { id: 'ur_' + '0'.repeat(24), segment: 0, checkpointRunId: 'aar_x', writePathsHash: '0'.repeat(64) } });
  assert.equal(spoof.status, 400, JSON.stringify(spoof.body));
  assert.equal(bridge.fetches().length, 0);
  assert.equal(bridge.read('src/app.js'), 'export const greeting = "hello";\n');
  noEgress(bridge); noSentinel(bridge);
});

test('the production authority refuses a writer run with no provider request and no write', { ...linuxOnly, timeout: 60000 }, async (t) => {
  const bridge = await writerBridge(t, { qualified: false });
  bridge.script([{ patch: { path: 'src/app.js', edits: [{ oldText: '"hello"', newText: '"bye"' }] } }, { text: 'done' }]);
  const created = await bridge.create(writerBody);
  if (created.status === 202) {
    await new Promise((resolve) => setTimeout(resolve, 6000));
    const v = await bridge.view(created.body.id);
    assert.notEqual(v.state, 'complete', JSON.stringify(v));
  } else {
    assert.ok([400, 409].includes(created.status), JSON.stringify(created.body));
  }
  assert.equal(bridge.fetches().length, 0);
  assert.equal(bridge.read('src/app.js'), 'export const greeting = "hello";\n');
  assert.equal(fs.existsSync(path.join(bridge.root, 'data', 'api-agent')) ? fs.readdirSync(path.join(bridge.root, 'data', 'api-agent')).length : 0, 0,
    'no API checkpoint is created');
  noEgress(bridge); noSentinel(bridge);
});

test('a writer or contract run with an authorized_prepaid entry is refused before any provider request', { ...linuxOnly, timeout: 60000 }, async (t) => {
  const bridge = await writerBridge(t);
  bridge.script([{ patch: { path: 'src/app.js', edits: [{ oldText: '"hello"', newText: '"bye"' }] } }, { text: 'done' }]);
  const native = { kind: 'codex', accountId: 'default', transport: 'native', model: 'gpt-5', effort: 'medium' };
  const prepaid = { ...bridge.apiSegment, fundingRoute: 'authorized_prepaid' };
  for (const [label, body] of [
    ['writer contract', { ...writerBody, segments: [native, prepaid] }],
    ['writer contract api-only', { ...writerBody, segments: [prepaid] }],
    ['dangerous only', { objective: 'x', dangerous: true, acknowledgeFilesystemWrites: true, segments: [native, prepaid] }],
  ]) {
    const refused = await bridge.create(body);
    assert.equal(refused.status, 409, `${label}: ${JSON.stringify(refused.body)}`);
    assert.equal(refused.body.code ?? refused.body.errorCode ?? refused.body.error, 'api_agent_read_only', `${label}: ${JSON.stringify(refused.body)}`);
  }
  assert.equal(fs.existsSync(path.join(bridge.root, 'data', 'unified-runs')) ? fs.readdirSync(path.join(bridge.root, 'data', 'unified-runs')).length : 0, 0);
  assert.equal(bridge.fetches().length, 0);
  assert.equal(bridge.read('src/app.js'), 'export const greeting = "hello";\n');
  noEgress(bridge); noSentinel(bridge);
});
