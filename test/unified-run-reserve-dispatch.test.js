async function reserveBridge(t, env = {}, { codexExhausted = false } = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'rb-reserve-fake-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const files = { modeFile: path.join(dir, 'mode'), gateFile: path.join(dir, 'gate'), fetchLog: path.join(dir, 'fetch.jsonl'),
    egressLog: path.join(dir, 'egress.log') };
  const preload = writePreload(dir, files);
  let ws;
  const bridge = await startTestBridge(t, (root) => {
    ws = path.join(root, 'ws'); fs.mkdirSync(ws, { recursive: true });
    return fixtureConfig(root, { codexExhausted });
  }, { nodeArgs: ['--require', preload], env: { RELAYBRIDGE_WARM_DIAG: '0', RELAYBRIDGE_REMOTE_MCP: '0',
    [CREDIT_SECRET_NAMES[1]]: SENTINEL, DENY_EGRESS_LOG: files.egressLog, ...env } });
  t.after(() => { try { fs.writeFileSync(path.join(bridge.root, 'release'), ''); } catch {} });
  // Each observation opens a later window so a lower reading is accepted.
  // `invalid` posts an out-of-range window, which leaves the seat's evidence
  // stale (native_evidence_invalid) rather than fresh.
  const baseReset = Math.floor(Date.now() / 1000) + 18000;
  let windowIndex = 0;
  const usage = async (kind, used, { invalid = false } = {}) => {
    const reset = baseReset + 60 * (++windowIndex);
    const result = await bridge.request('/api/usage/native', { kind, accountId: 'default', rate_limits: {
      five_hour: { used_percentage: invalid ? 150 : used, resets_at: reset }, seven_day: { used_percentage: used, resets_at: reset + 604800 } } });
    assert.equal(result.status, 200, JSON.stringify(result.body));
    assert.equal(result.body.observed, true, JSON.stringify(result.body));
    assert.equal(result.body.usage.freshness, invalid ? 'stale' : 'fresh', JSON.stringify(result.body));
  };
  const saved = await bridge.request('/api/funding-profiles', { expectedRevision: (await bridge.request('/api/funding-profiles')).body.storeRevision,
    profile: { id: 'api_openai', provider: 'openai', label: 'api_openai', subscription: { kind: 'codex', accountId: 'default' },
      organization: { ref: 'org_api_openai', label: 'Fixture org' }, project: { ref: 'project_api_openai', label: 'Fixture project' },
      credentialRef: { type: 'reserved_env', name: CREDIT_SECRET_NAMES[1] },
      creditPeriod: { start: '2020-01-01T00:00:00.000Z', end: '2099-01-01T00:00:00.000Z' } } });
  assert.equal(saved.status, 200, JSON.stringify(saved.body));
  const revision = saved.body.profiles?.find?.((p) => p.id === 'api_openai')?.revision ?? 1;
  const segments = [{ kind: 'claude', accountId: 'default', transport: 'native', model: 'fixture', effort: 'low' },
    { kind: 'codex', accountId: 'default', transport: 'api', model: 'gpt-5', effort: 'medium', fundingProfileId: 'api_openai', expectedProfileRevision: revision }];
  const events = () => completeJsonLines(path.join(bridge.root, 'events.jsonl'));
  const claudeEvents = () => events().filter((e) => e.kind === 'claude');
  const fetches = () => completeJsonLines(files.fetchLog);
  const manifestPath = (id) => path.join(bridge.root, 'data', 'unified-runs', id, 'manifest.json');
  const manifest = (id) => JSON.parse(fs.readFileSync(manifestPath(id), 'utf8'));
  const view = async (id) => (await bridge.request(`/api/unified-runs/${id}`)).body;
  const create = async (objective) => {
    const created = await bridge.request('/api/unified-runs', { objective, cwd: ws, segments });
    assert.equal(created.status, 202, JSON.stringify(created.body));
    return created.body.id;
  };
  // The API segment settles, its release is recorded, and the run either
  // plans the reserve segment or waits.
  const released = (id) => waitFor(async () => {
    const m = manifest(id);
    return m.reserveRelease && m.segments[0]?.state === 'settled' && m.state === 'waiting_for_quota' && m;
  }, 20000);
  // Rewrite the stored release binding, retrying if a concurrent save of the
  // bridge's own copy replaced it.
  const forge = async (id, patch, releasePatch = {}) => {
    for (let attempt = 0; attempt < 10; attempt++) {
      const m = manifest(id);
      m.reserveRelease = { ...m.reserveRelease, ...releasePatch, binding: { ...m.reserveRelease.binding, ...patch } };
      fs.writeFileSync(manifestPath(id), JSON.stringify(m, null, 2));
      await new Promise((resolve) => setTimeout(resolve, 300));
      const stored = manifest(id).reserveRelease.binding;
      if (Object.entries(patch).every(([key, value]) => stored[key] === value)) return;
    }
    assert.fail('the forged binding did not persist');
  };
  const segmentTask = async (id, index) => {
    const m = await waitFor(() => { const value = manifest(id); return value.segments[index]?.taskId && value; }, 20000);
    return m.segments[index].taskId;
  };
  const taskSettled = (taskId) => waitFor(async () => {
    const task = (await bridge.request(`/api/tasks/${taskId}`)).body;
    return ['done', 'failed', 'cancelled', 'stopped'].includes(task.status) && task;
  }, 25000);
  // Two continuity ticks (5s each) pass with no further dispatch.
  const quiet = () => new Promise((resolve) => setTimeout(resolve, 11000));
  return { ...bridge, ws, files, revision, usage, forge, events, claudeEvents, fetches, manifest, manifestPath, view, create, released, segmentTask, taskSettled, quiet };
}

const noEgress = (bridge) => assert.equal(fs.existsSync(bridge.files.egressLog) ? fs.readFileSync(bridge.files.egressLog, 'utf8') : '', '');
const noSentinel = (bridge) => {
  const walk = (dir) => fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => e.isDirectory() ? walk(path.join(dir, e.name)) : e.isFile() ? [path.join(dir, e.name)] : []) : [];
  for (const file of walk(path.join(bridge.root, 'data'))) assert.equal(fs.readFileSync(file, 'utf8').includes(SENTINEL), false, file);
};

