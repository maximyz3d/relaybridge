test('a funding-exhausted API segment releases the native reserve through real dispatch at 2% and 1%, consumed once', { ...linuxOnly, timeout: 120000 }, async (t) => {
  const bridge = await reserveBridge(t);
  for (const used of [98, 99]) {
    await bridge.usage('claude', used);
    const before = bridge.claudeEvents().length;
    const id = await bridge.create(`Review at ${used}`);
    const done = await waitFor(async () => { const v = await bridge.view(id); return v.state === 'complete' && v; }, 30000);
    assert.deepEqual(done.segments.map((s) => s.phase), ['api', 'reserve'], JSON.stringify(done));
    assert.equal(bridge.claudeEvents().length, before + 1, 'exactly one native reserve dispatch');
    const m = bridge.manifest(id);
    assert.equal(m.reserveRelease.qualificationId, 'q_test_fake');
    assert.equal(m.reserveRelease.consumedBy, m.segments[1].taskId);
    const api = (await bridge.request(`/api/tasks/${m.segments[0].taskId}`)).body;
    assert.equal(api.route?.funding?.qualificationId ?? api.result?.route?.funding?.qualificationId, 'q_test_fake', JSON.stringify(api));
    // The reserve task carried no client-visible authority: its body binds only account and seat.
    const reserve = (await bridge.request(`/api/tasks/${m.segments[1].taskId}`)).body;
    const body = reserve.body || reserve.input || reserve;
    assert.equal(Object.hasOwn(body, 'reserveRelease'), false);
    assert.equal(body.expectedAccountId, 'default'); assert.equal(body.expectedQuotaSeat, 'claude'); assert.equal(body.requireFreshUsage, true);
    // A consumed release never admits a second reserve segment.
    await bridge.quiet();
    assert.equal(bridge.claudeEvents().length, before + 1);
  }
  assert.equal(bridge.fetches().length, 2);
  assert.ok(bridge.fetches().every((f) => f.host === 'api.openai.com' && f.mode === 'exhausted'));
  noEgress(bridge); noSentinel(bridge);
});

test('the reserve is refused at selection for 0%, stale usage, a forged binding and a generic provider failure', { ...linuxOnly, timeout: 150000 }, async (t) => {
  const bridge = await reserveBridge(t);

  // 0%: the release is recorded but the native seat has no headroom.
  await bridge.usage('claude', 100);
  const empty = await bridge.create('Review empty');
  await bridge.released(empty);
  await bridge.quiet();
  let v = await bridge.view(empty);
  assert.notEqual(v.state, 'complete', JSON.stringify(v));
  assert.equal(v.segments.length, 1, JSON.stringify(v));
  assert.equal(bridge.claudeEvents().length, 0);

  // Stale: invalid evidence for the seat; the release never falls back to stale evidence.
  await bridge.usage('claude', 98, { invalid: true });
  await bridge.quiet();
  v = await bridge.view(empty);
  assert.equal(v.segments.length, 1, JSON.stringify(v));
  assert.equal(bridge.claudeEvents().length, 0);

  // Forged release: a self-consistent manifest naming another qualification
  // still never matches the live qualification.
  assert.equal((await bridge.request(`/api/unified-runs/${empty}/cancel`, {})).body.state, 'cancelled');
  await bridge.usage('claude', 100);
  const forged = await bridge.create('Review forged');
  await bridge.released(forged);
  await bridge.forge(forged, { qualificationId: 'q_forged' }, { qualificationId: 'q_forged' });
  await bridge.usage('claude', 98);
  await bridge.quiet();
  v = await bridge.view(forged);
  assert.equal(v.segments.length, 1, JSON.stringify(v));
  assert.equal(bridge.claudeEvents().length, 0);
  await bridge.request(`/api/unified-runs/${forged}/cancel`, {});

  // Generic provider failure (429 rate limit): no release, so no reserve.
  fs.writeFileSync(bridge.files.modeFile, 'rate');
  const limited = await bridge.create('Review limited');
  await waitFor(() => { const value = bridge.manifest(limited); return value.segments[0]?.state === 'settled' && value; }, 20000);
  await bridge.quiet();
  assert.equal(bridge.manifest(limited).reserveRelease ?? null, null);
  assert.equal((await bridge.view(limited)).segments.length, 1);
  assert.equal(bridge.claudeEvents().length, 0);

  // Public clients cannot supply the release or the run reference.
  for (const route of ['/api/oneshot', '/api/tasks']) {
    for (const extra of [{ unifiedRun: { id: forged, segment: 1 } }, { reserveRelease: { reserveReleaseEvidence: true } }]) {
      const refused = await bridge.request(route, { kind: 'claude', prompt: 'spoof', cwd: bridge.ws, expectedAccountId: 'default', ...extra });
      assert.equal(refused.status, 400, `${route} ${JSON.stringify(refused.body)}`);
    }
  }
  assert.equal(bridge.claudeEvents().length, 0);
  noEgress(bridge); noSentinel(bridge);
});

test('the dispatch gate re-proves the reserve: a queued reserve task is refused at 0%, stale and forged evidence', { ...linuxOnly, timeout: 200000 }, async (t) => {
  const bridge = await reserveBridge(t, { RELAYBRIDGE_MAX_TASKS: '1' });
  const release = path.join(bridge.root, 'release');
  for (const variant of ['zero', 'stale', 'forged']) {
    fs.rmSync(release, { force: true });
    await bridge.usage('claude', 98);
    fs.writeFileSync(bridge.files.gateFile, '');
    const id = await bridge.create(`Review gate ${variant}`);
    // The API segment is in flight (its provider call is held); queue a blocker behind it.
    await waitFor(() => { const value = bridge.manifest(id); return value.segments[0]?.state === 'dispatched' && value; }, 20000);
    const blocker = await bridge.request('/api/tasks', { kind: 'codex', prompt: `HOLD blocker ${variant}`, cwd: bridge.ws, effort: 'low' });
    assert.ok([200, 202].includes(blocker.status), JSON.stringify(blocker.body));
    fs.rmSync(bridge.files.gateFile);
    await waitFor(() => bridge.events().some((e) => e.kind === 'codex' && e.prompt.includes(`blocker ${variant}`)), 20000);
    // The reserve segment is planned with fresh 2% evidence and waits in the queue.
    const reserveTaskId = await bridge.segmentTask(id, 1);
    const queued = (await bridge.request(`/api/tasks/${reserveTaskId}`)).body;
    assert.equal(queued.status, 'queued', JSON.stringify(queued));
    if (variant === 'zero') await bridge.usage('claude', 100);
    if (variant === 'stale') await bridge.usage('claude', 98, { invalid: true });
    if (variant === 'forged') await bridge.forge(id, { credentialFingerprint: 'forged' });
    const before = bridge.claudeEvents().length;
    fs.writeFileSync(release, '');
    const task = await bridge.taskSettled(reserveTaskId);
    assert.notEqual(task.status, 'done', JSON.stringify(task));
    assert.match(JSON.stringify(task), /quota_reserve|quota_unknown|reserve_release_unavailable/, `${variant}: ${JSON.stringify(task)}`);
    assert.equal(bridge.claudeEvents().length, before, `${variant}: the reserve task never reached the provider`);
    await bridge.quiet();
    assert.equal(bridge.claudeEvents().length, before, `${variant}: no automatic retry`);
  }
  noEgress(bridge); noSentinel(bridge);
});

test('supervision stops a running reserve segment once 0%, stale or forged evidence replaces fresh headroom', { ...linuxOnly, timeout: 200000 }, async (t) => {
  const bridge = await reserveBridge(t);
  const release = path.join(bridge.root, 'release');
  for (const variant of ['zero', 'stale', 'forged']) {
    fs.rmSync(release, { force: true });
    await bridge.usage('claude', 98);
    const before = bridge.claudeEvents().length;
    const id = await bridge.create(`Review HOLD ${variant}`);
    await waitFor(() => bridge.claudeEvents().length === before + 1, 25000)
      .catch(async (error) => assert.fail(`${variant}: ${error.message}: ${JSON.stringify(bridge.manifest(id))} ${JSON.stringify(bridge.events())}`));
    const reserveTaskId = bridge.manifest(id).segments[1].taskId;
    if (variant === 'zero') await bridge.usage('claude', 100);
    if (variant === 'stale') await bridge.usage('claude', 98, { invalid: true });
    if (variant === 'forged') await bridge.forge(id, { profileRevision: bridge.manifest(id).reserveRelease.binding.profileRevision + 1 });
    const task = await bridge.taskSettled(reserveTaskId);
    assert.notEqual(task.status, 'done', `${variant}: ${JSON.stringify(task)}`);
    assert.match(JSON.stringify(task), /quota_reserve/, `${variant}: ${JSON.stringify(task)}`);
    fs.writeFileSync(release, '');
    await bridge.quiet();
    assert.equal(bridge.claudeEvents().length, before + 1, `${variant}: no automatic retry`);
  }
  noEgress(bridge); noSentinel(bridge);
});

// A permit valid now for the fixture profile: inside the current UTC month, at most 24h.
function livePermit(revision) {
  const { credentialHmac, PREPAID_POLICY } = require('../lib/prepaid-authorization');
  const now = Date.now(), d = new Date(now);
  const monthStart = Date.UTC(d.getUTCFullYear(), d.getUTCMonth(), 1), nextMonth = Date.UTC(d.getUTCFullYear(), d.getUTCMonth() + 1, 1);
  const issued = Math.max(now - 60000, monthStart), expires = Math.min(issued + 23 * 3600e3, nextMonth);
  const observed = new Date(issued - 3600e3).toISOString();
  return { schemaVersion: 1, authorizationId: 'pa_reserve_1', policy: PREPAID_POLICY, provider: 'openai', surface: 'openai_responses_agent',
    supervised: true, noPurchases: true, profileId: 'api_openai', profileRevision: revision, organization: 'org_api_openai',
    project: 'project_api_openai', credentialHmac: credentialHmac('pa_reserve_1', SENTINEL), models: ['gpt-5'], issuedAt: new Date(issued).toISOString(),
    expiresAt: new Date(expires).toISOString(), revokedAt: null,
    providerControls: { autoReload: 'off', hardLimitCents: 12000, hardLimitScope: 'organization', hardLimitEnforced: true, observedAt: observed },
    balance: { observedBalanceCents: 20100, observedAt: observed, earliestCreditExpiry: new Date(expires + 2 * 86400e3).toISOString().slice(0, 10) } };
}

test('an exhausted prepaid segment never releases the native reserve, even with a qualified grant authority present', { ...linuxOnly, timeout: 90000 }, async (t) => {
  const bridge = await reserveBridge(t, {}, { codexExhausted: true });
  fs.writeFileSync(path.join(bridge.root, 'data', 'prepaid-authorization.json'), JSON.stringify(livePermit(bridge.revision)), { mode: 0o600 });
  await waitFor(async () => (await bridge.request('/api/usage/native')).body.observations
    .some((o) => String(o.quotaSeat).startsWith('codex')), 15000);
  await bridge.usage('claude', 100);
  const created = await bridge.request('/api/unified-runs', { objective: 'Review prepaid', cwd: bridge.ws, segments: [
    { kind: 'claude', accountId: 'default', transport: 'native', model: 'fixture', effort: 'low' },
    { kind: 'codex', accountId: 'default', transport: 'native', model: 'gpt-5', effort: 'medium' },
    { kind: 'codex', accountId: 'default', transport: 'api', model: 'gpt-5', effort: 'medium', fundingProfileId: 'api_openai',
      expectedProfileRevision: bridge.revision, fundingRoute: 'authorized_prepaid' }] });
  assert.equal(created.status, 202, JSON.stringify(created.body));
  const id = created.body.id;
  const m = await waitFor(() => { const value = bridge.manifest(id); return value.segments[0]?.state === 'settled' && value.state === 'waiting_for_quota' && value; }, 20000);
  assert.equal(m.segments[0].outcome, 'funding_exhausted', JSON.stringify(m.segments[0]));
  assert.equal(m.segments[0].prepaidBinding.authorizationId, 'pa_reserve_1');
  assert.equal(m.reserveRelease ?? null, null);
  // 2% remaining is the protected band: a grant release would spend it, prepaid exhaustion does not.
  await bridge.usage('claude', 98);
  await bridge.quiet();
  const after = bridge.manifest(id);
  assert.equal(after.segments.length, 1, JSON.stringify(after.segments));
  assert.equal(after.reserveRelease ?? null, null);
  assert.equal(bridge.claudeEvents().length, 0);
  assert.equal(bridge.fetches().length, 1);
  noEgress(bridge); noSentinel(bridge);
});
